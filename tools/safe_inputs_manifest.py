def verify(root, support):
    records = []

    def check(path, expected, purpose, origin, actual_path):
        try:
            actual = hashlib.sha256(actual_path.read_bytes()).hexdigest()
            error = None if actual == expected else "SHA-256 mismatch"
        except OSError as exc:
            actual, error = None, str(exc)
        records.append(dict(path=path, sha256=expected, actual_sha256=actual,
                            purpose=purpose, provenance=origin, error=error))

    if not FILES or not FX_REPLAY:
        raise ValueError("empty input manifest")
    paths = [row[0] for row in FILES] + [row[0] for row in FX_REPLAY]
    if len(paths) != len(set(paths)):
        raise ValueError("duplicate manifest path")
    for path, digest, purpose, origin in FILES:
        check(path, digest, purpose, origin, root / path)
    with tempfile.TemporaryDirectory(prefix="cna-safe-replay-") as scratch:
        for name, digest, mode, purpose in FX_REPLAY:
            path = Path(scratch) / name
            if mode is None:
                path.write_bytes(b"refused effect")
            else:
                subprocess.run([str(support), mode, str(path)], check=True, timeout=15)
            check(name, digest, purpose, "CNA synthetic fixed replay; MS-PL", path)
    return dict(schema_version=1, qualification="input_provenance_only",
                checked=len(records), failures=sum(row["error"] is not None for row in records),
                inputs=records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--fx-support", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = verify(args.root.resolve(), args.fx_support.resolve())
    output = json.dumps(report, indent=2) + "\n"
    if args.output:
        args.output.write_text(output, encoding="utf-8")
    print(output, end="")
    return int(report["failures"] != 0)


if __name__ == "__main__":
    raise SystemExit(main())
