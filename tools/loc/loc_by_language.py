# Plain-text rendering of the Markdown report, for a terminal

LINK = re.compile(r"\[([^\]]+)\]\([^)]+\)")           # [text](link) -> text
INLINE_MARKUP = (
    (re.compile(r"\*\*([^*]+)\*\*"), r"\1"),          # **bold**
    (re.compile(r"(?<![\w*])\*([^*\s][^*]*)\*(?![\w*])"), r"\1"),  # *italic*
)
NBSP = "\u00a0"


def plain(text: str) -> str:
    """Drop Markdown emphasis and links; `code` spans lose their backticks but keep their text."""
    parts = re.split(r"(`[^`]*`)", LINK.sub(r"\1", text))
    for index, part in enumerate(parts):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            parts[index] = part[1:-1]
            continue
        for pattern, replacement in INLINE_MARKUP:
            part = pattern.sub(replacement, part)
        parts[index] = part
    return "".join(parts).replace("\\|", "|")


def wrap(text: str, width: int, **kwargs) -> list[str]:
    """textwrap.wrap that never breaks inside "12 345", "84.2 %" or "0.74 : 1"."""
    glued = re.sub(r"(?<=\d) (?=\d{3}\b)|(?<=\d) (?=%)|(?<=\d) : (?=\d)",
                   lambda m: m.group(0).replace(" ", NBSP), text)
    return [line.replace(NBSP, " ") for line in textwrap.wrap(glued, width, **kwargs)]


def text_table(lines: list[str]) -> list[str]:
    def cells(line: str) -> list[str]:
        return [c.strip() for c in re.split(r"(?<!\\)\|", line.strip()[1:-1])]

    header, marks, body = cells(lines[0]), cells(lines[1]), [cells(line) for line in lines[2:]]
    right = [m.endswith(":") and not m.startswith(":") for m in marks]
    emphasised = [row[0].startswith("**") for row in body]
    header = [plain(c) for c in header]
    body = [[plain(c) for c in row] for row in body]
    widths = [max(len(row[i]) for row in [header] + body) for i in range(len(header))]

    def fmt(row: list[str]) -> str:
        return "  ".join(c.rjust(w) if r else c.ljust(w) for c, w, r in zip(row, widths, right)).rstrip()

    rule = "  ".join("-" * w for w in widths)
    out = [fmt(header), rule]
    for row, strong in zip(body, emphasised):
        if strong and out[-1] != rule:
            out.append(rule)
        out.append(fmt(row))
    return out


def markdown_to_text(markdown: str, width: int) -> str:
    out: list[str] = []
    lines = markdown.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("|"):
            block = []
            while i < len(lines) and lines[i].startswith("|"):
                block.append(lines[i])
                i += 1
            out += text_table(block)
            continue
        if line.startswith("```"):
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                out.append("    " + lines[i])
                i += 1
            i += 1
            continue
        heading = re.match(r"(#+) (.*)", line)
        if heading:
            level, title = len(heading.group(1)), plain(heading.group(2))
            if level == 1:
                out += [title, "=" * len(title)]
            elif level == 2:
                out += [title, "-" * len(title)]
            else:
                out += [title + ":"]
        elif line.startswith("- "):
            out += wrap(plain(line[2:]), width, initial_indent="- ", subsequent_indent="  ")
        elif line:
            out += wrap(plain(line), width)
        else:
            out.append("")
        i += 1
    return "\n".join(out).rstrip() + "\n"


