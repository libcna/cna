# Markdown rendering

def n(value: int) -> str:
    return f"{value:,}".replace(",", " ")


def pct(part: int, whole: int) -> str:
    return f"{100.0 * part / whole:.1f} %" if whole else "-"


def kind_of(language: str) -> str:
    return LANGUAGE_KIND.get(language, DATA)


def table(header: list[str], rows: list[list[str]], align: str) -> list[str]:
    marks = {"l": ":---", "r": "---:"}
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(marks[a] for a in align) + " |"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out


def counts_row(label: str, c: Counts, total_code: int | None = None) -> list[str]:
    row = [label, n(c.files), n(c.blank), n(c.comment), n(c.code), pct(c.comment, c.comment + c.code)]
    if total_code is not None:
        row.append(pct(c.code, total_code))
    return row


COUNT_HEADER = ["Files", "Blank", "Comment", "Code", "Comment ratio"]


def aggregate(records, key) -> dict:
    result: dict = defaultdict(Counts)
    for record in records:
        result[key(record)].add(record.counts)
    return result


def sums_of(records, predicate) -> Counts:
    c = Counts()
    for r in records:
        if predicate(r):
            c.add(r.counts)
    return c


def src_by_cat_first(records, key: str) -> int:
    return sum(r.counts.code for r in records if r.category == key)


def render(report: Report) -> str:
    out: list[str] = []
    first = [r for r in report.records if CATEGORY_BY_KEY[r.category].first_party]
    third = [r for r in report.records if not CATEGORY_BY_KEY[r.category].first_party]
    first_source = [r for r in first if kind_of(r.language) in SOURCE_KINDS]
    handwritten = [r for r in first_source if not r.generated]

    def total(records) -> Counts:
        c = Counts()
        for r in records:
            c.add(r.counts)
        return c

    t_data = total(r for r in first if kind_of(r.language) == DATA)
    out += [
        "# CNA lines-of-code analysis",
        "",
        f"Generated by `tools/loc/loc_by_language.py` from commit `{report.head}` on "
        f"{report.date}, with cloc as the counting engine. Every git-tracked "
        "file is counted once (duplicates included); a *code* line is a line with anything other "
        "than whitespace or a comment, a *comment* line holds only a comment, and a *blank* line "
        "holds only whitespace. *Comment ratio* is comment / (comment + code).",
        "",
        "**Source code** below means programming languages, shaders and build/config languages "
        "(CMake, YAML, TOML, ...). Markup (Markdown, HTML, plain text) and data (JSON, glTF, XML, "
        "CSV, patches, DirectX `.x` models) are counted too, but reported beside the source code "
        f"rather than added into it: {n(t_data.code)} lines of first-party data (test fixtures, "
        "generated JSON reports) would otherwise drown everything written by hand.",
        "",
        "## Headline numbers",
        "",
    ]
    t_first, t_source, t_hand = total(first), total(first_source), total(handwritten)
    cpp_languages = ("C++", "C++ Header")
    t_cpp = total(r for r in first_source if r.category == "library" and r.language in cpp_languages and not r.generated)
    t_third = total(r for r in third if kind_of(r.language) in SOURCE_KINDS)
    out += table(
        ["Measure", "Files", "Code lines"],
        [
            ["CNA first-party, all languages incl. markup & data", n(t_first.files), n(t_first.code)],
            ["CNA first-party **source code**", n(t_source.files), f"**{n(t_source.code)}**"],
            ["... of which hand-written (generated files excluded)", n(t_hand.files), n(t_hand.code)],
            ["... of which the production library in C++ (`.cpp`/`.hpp`, hand-written)", n(t_cpp.files), n(t_cpp.code)],
            ["Third-party source code (vendored + submodules, not CNA's)", n(t_third.files), n(t_third.code)],
        ],
        "lrr",
    )
    out.append("")

    # --- Bridge from the headline to production C++ --------------------------------------
    library = [r for r in first_source if r.category == "library"]
    library_cpp = [r for r in library if r.language in cpp_languages]
    library_cpp_hand = [r for r in library_cpp if not r.generated]
    library_cpp_hand_no_capi = [r for r in library_cpp_hand if r.component != "c-api"]
    other_categories = [c for c in CATEGORIES if c.first_party and c.key != "library" and src_by_cat_first(first_source, c.key)]
    steps = [["CNA first-party source code, every category and language", "", f"**{n(t_source.code)}**"]]
    for cat in other_categories:
        steps.append([f"minus {cat.title}", f"-{n(src_by_cat_first(first_source, cat.key))}", ""])
    steps.append(["= production library, every language", "", f"**{n(total(library).code)}**"])
    non_cpp = defaultdict(int)
    for r in library:
        if r.language not in cpp_languages:
            non_cpp[r.language] += r.counts.code
    steps.append(["minus its non-C++ files (listed below)", f"-{n(sum(non_cpp.values()))}", ""])
    steps.append(["= production library in C++ (`.cpp` + `.hpp`)", "", f"**{n(total(library_cpp).code)}**"])
    steps.append(["minus generated C++ (C API routes, embedded shader bytecode)",
                  f"-{n(total(library_cpp).code - total(library_cpp_hand).code)}", ""])
    steps.append(["= hand-written production C++", "", f"**{n(total(library_cpp_hand).code)}**"])
    steps.append(["minus the hand-written C ABI layer (`modules/c-api`)",
                  f"-{n(total(library_cpp_hand).code - total(library_cpp_hand_no_capi).code)}", ""])
    steps.append(["= hand-written production C++ without the C API", "",
                  f"**{n(total(library_cpp_hand_no_capi).code)}**"])
    out += ["## From the headline to production C++", "",
            "How the all-source-code total narrows down to the C++ engine itself; every figure is "
            "code lines only (no blank lines, no comments).", ""]
    out += table(["Step", "Change", "Code lines"], steps, "lrr")
    out += ["", "The library's non-C++ files: " + ", ".join(
        f"{l} {n(v)}" for l, v in sorted(non_cpp.items(), key=lambda kv: -kv[1]))
        + " (`C/C++ Header` is the C API's `.h`).", ""]

    # --- C++ at a glance -----------------------------------------------------------------
    cpp_records = [r for r in first_source if r.language in cpp_languages]

    def cpp_row(label: str, predicate) -> list[str]:
        c = sums_of(cpp_records, predicate)
        return [label, n(c.files), n(c.blank), n(c.comment), f"**{n(c.code)}**"]

    in_library = lambda r: r.category == "library"
