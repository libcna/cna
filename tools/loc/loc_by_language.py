# Change report between two commits

@dataclass
class CommitDelta:
    commit: str
    subject: str
    before: Report
    after: Report


def signed(value: int) -> str:
    return f"{value:+,}".replace(",", " ") if value else "0"


def signed_pct(before: int, after: int) -> str:
    return f"{100.0 * (after - before) / before:+.1f} %" if before else "-"


def sums(records, predicate=lambda r: True) -> Counts:
    c = Counts()
    for r in records:
        if predicate(r):
            c.add(r.counts)
    return c


def first_party(report: Report) -> list[FileRecord]:
    return [r for r in report.records if CATEGORY_BY_KEY[r.category].first_party]


def is_source(r: FileRecord) -> bool:
    return kind_of(r.language) in SOURCE_KINDS


def commit_deltas(base: str, target: str, workdir: Path) -> list[CommitDelta]:
    """Count, for every first-parent commit in base..target, the files it changed before and after."""
    deltas = []
    commits = git("rev-list", "--first-parent", "--reverse", f"{base}..{target}").split()
    for index, commit in enumerate(commits):
        parent = f"{commit}^1"
        changed = [p for p in git("diff", "--name-only", "-z", "--no-renames", parent, commit).split("\0")
                   if p and p not in SUBMODULES]
        old_paths = set(git("ls-tree", "-r", "-z", "--name-only", parent, "--",
                            *[f":(literal){p}" for p in changed]).split("\0")) if changed else set()
        new_paths = set(git("ls-tree", "-r", "-z", "--name-only", commit, "--",
                            *[f":(literal){p}" for p in changed]).split("\0")) if changed else set()
        before_dir, after_dir = workdir / f"{index}-before", workdir / f"{index}-after"
        before_dir.mkdir()
        after_dir.mkdir()
        before = build_report(revision_tree(parent, before_dir, sorted(p for p in old_paths if p)))
        after = build_report(revision_tree(commit, after_dir, sorted(p for p in new_paths if p)))
        shutil.rmtree(before_dir)
        shutil.rmtree(after_dir)
        subject = git("log", "-1", "--format=%s", commit).strip()
        deltas.append(CommitDelta(git("rev-parse", "--short", commit).strip(), subject, before, after))
    return deltas


