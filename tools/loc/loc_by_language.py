@dataclass
class Counts:
    files: int = 0
    blank: int = 0
    comment: int = 0
    code: int = 0

    def add(self, other: "Counts") -> None:
        self.files += other.files
        self.blank += other.blank
        self.comment += other.comment
        self.code += other.code

    @property
    def lines(self) -> int:
        return self.blank + self.comment + self.code


@dataclass
class FileRecord:
    path: str
    language: str
    counts: Counts
    category: str
    component: str  # module name, third-party component, or top-level tree
    tree: str = ""  # module subtree (include/src/tests/...) for module files
    generated: bool = False


@dataclass
class Report:
    records: list[FileRecord] = field(default_factory=list)
    uncounted: dict[str, Counter] = field(default_factory=lambda: defaultdict(Counter))  # category -> suffixes cloc skipped
    missing_submodules: list[str] = field(default_factory=list)
    head: str = ""
    date: str = ""
    subject: str = ""
    first_party_bytes: int = 0


def git(*args: str, cwd: Path = ROOT) -> str:
    return subprocess.run(("git", *args), cwd=cwd, check=True, capture_output=True, text=True).stdout


@dataclass
class Tree:
    """The files to count and the directory their repository-relative paths resolve against."""
    root: Path
    files: list[str]
    label: str
    date: str
    subject: str = ""
    missing_submodules: list[str] = field(default_factory=list)
    first_party_bytes: int = 0


def submodule_paths(rev: str | None = None) -> list[str]:
    if rev is None and not (ROOT / ".gitmodules").is_file():
        return []
    source = ("--blob", f"{rev}:.gitmodules") if rev else ("--file", ".gitmodules")
    try:
        out = git("config", *source, "--get-regexp", r"submodule\..*\.path")
    except subprocess.CalledProcessError:
        return []
    return sorted(line.split(" ", 1)[1] for line in out.splitlines() if " " in line)


def submodule_head(sub: str) -> str | None:
    if not (ROOT / sub / ".git").exists():
        return None
    return git("rev-parse", "HEAD", cwd=ROOT / sub).strip()


def submodule_files(sub: str) -> list[str]:
    return [f"{sub}/{p}" for p in git("ls-files", "-z", cwd=ROOT / sub).split("\0") if p]


def working_tree() -> Tree:
    submodules = submodule_paths()
    SUBMODULES.update(submodules)
    tree = Tree(ROOT, [], git("rev-parse", "--short", "HEAD").strip(), datetime.date.today().isoformat())
    files = [p for p in git("ls-files", "-z").split("\0") if p and p not in submodules]
    for sub in submodules:
        if not COUNT_SUBMODULES:
            continue
        if submodule_head(sub) is None:
            tree.missing_submodules.append(sub)
        else:
            files += submodule_files(sub)
    tree.files = [p for p in files if (ROOT / p).is_file() and not (ROOT / p).is_symlink()]
    return tree


def revision_tree(rev: str, workdir: Path, paths: list[str] | None = None) -> Tree:
    """Extract a commit (or only `paths` of it) into workdir and describe it as a Tree.

    A whole-commit tree counts a submodule only when the checked-out submodule is the commit the
    superproject pinned at `rev`; a `paths` subset never includes submodules.
    """
    subs = submodule_paths(rev)
    SUBMODULES.update(subs)
    label = git("rev-parse", "--short", rev).strip()
    date, subject = git("log", "-1", "--format=%cs%x00%s", rev).rstrip("\n").split("\0", 1)
    tree = Tree(workdir, [], label, date, subject)
    specs = [f":(literal){p}" for p in paths] if paths is not None else []
    if paths is not None and not paths:
        return tree
    files, gitlinks = [], {}
    for entry in git("ls-tree", "-r", "-l", "-z", rev, "--", *specs).split("\0"):
        if not entry:
            continue
        meta, path = entry.split("\t", 1)
        mode, kind, sha, size = meta.split()
        if kind == "commit":
            gitlinks[path] = sha
        elif kind == "blob" and mode != "120000":
            files.append(path)
            if CATEGORY_BY_KEY[classify(path)[0]].first_party:
                tree.first_party_bytes += int(size)
    archive = subprocess.Popen(("git", "archive", "--format=tar", rev, "--", *specs),
                               cwd=ROOT, stdout=subprocess.PIPE)
    with tarfile.open(fileobj=archive.stdout, mode="r|") as tar:
        if hasattr(tarfile, "data_filter"):
            tar.extractall(workdir, filter="data")
        else:
            tar.extractall(workdir)
    if archive.wait() != 0:
        sys.exit(f"error: git archive {rev} failed")
    if paths is None and COUNT_SUBMODULES:
        for sub, sha in sorted(gitlinks.items()):
            if submodule_head(sub) != sha:
                tree.missing_submodules.append(sub)
                continue
            target = workdir / sub
            if target.is_dir():
                target.rmdir()
            target.parent.mkdir(parents=True, exist_ok=True)
            target.symlink_to(ROOT / sub, target_is_directory=True)
            files += submodule_files(sub)
    tree.files = [p for p in files if (workdir / p).is_file()]
    return tree


def classify(path: str) -> tuple[str, str, str]:
    """Return (category, component, module subtree) for a repository-relative path."""
    parts = PurePosixPath(path).parts
    top = parts[0]
    name = parts[-1]

    if top in ("third_party", "vendor") and len(parts) > 1:
        component = parts[1]
        sub = f"{top}/{component}"
        category = "submodules" if sub in SUBMODULES else "vendored"
        return category, component, ""

    if top == "modules" and len(parts) > 2:
        # The module root is the directory just above the first well-known subtree, so nested
        # modules such as modules/renderers/common/mojoshader resolve correctly.
        for index in range(1, len(parts) - 1):
            tree = parts[index]
            if tree in MODULE_TREES:
                module = "/".join(parts[1:index])
                if tree in MODULE_TREES_LIBRARY:
                    return "library", module, tree
                if tree == "cmake":
                    return "build", module, tree
                return tree, module, tree
        module = "/".join(parts[1:-1])
        if name == "CMakeLists.txt":
            return "build", module or "(modules root)", ""
        if "test" in name:
            return "tests", module, "tests"
        return "library", module, ""
    if top == "modules":
        return "build", "(modules root)", ""

    if top == "tests":
        return "tests", "tests/" + (parts[1] if len(parts) > 2 else ""), ""
    if top == "examples":
        return "examples", "examples", ""
    if top == "tools":
        return "tools", "tools/" + (parts[1] if len(parts) > 2 else "(top-level files)"), ""
    if top == "scripts" or path == "loc.sh":
        return "scripts", "scripts", ""
    if top == "spikes":
        return "spikes", "spikes/" + parts[1] if len(parts) > 2 else "spikes", ""
    if top == ".github":
        return "ci", ".github", ""
    if top == "cmake":
        if len(parts) > 2 and parts[1] == "patches" and name.endswith(".patch"):
            return "patches", "cmake/patches", ""
        return "build", "cmake", ""
    if path in ("CMakeLists.txt", "CMakePresets.json"):
        return "build", "(root)", ""
    if top in ("docs", "plans", "misc", "remediation", ".claude"):
        return "docs", top, ""
    if len(parts) == 1 and name.lower().endswith(".md"):
        return "docs", "(root)", ""
    return "other", "(root)", ""



def is_generated(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            head = [handle.readline() for _ in range(12)]
    except OSError:
        return False
    for line in head:
        stripped = line.strip()
        if stripped.startswith(COMMENT_LEADS) and any(m in stripped.lower() for m in GENERATED_MARKERS):
            return True
    return False


def run_cloc(files: list[str], cwd: Path) -> dict:
    cloc = shutil.which("cloc")
    if cloc is None:
        sys.exit("error: cloc is required (https://github.com/AlDanial/cloc; apt-get install cloc)")
    with tempfile.TemporaryDirectory() as tmp:
        list_file = Path(tmp) / "files.txt"
        out_file = Path(tmp) / "cloc.json"
        list_file.write_text("\n".join(files) + "\n", encoding="utf-8")
        command = [cloc, f"--list-file={list_file}", "--by-file", "--json", "--quiet",
                   "--skip-uniqueness", f"--out={out_file}"]
        command += [f"--force-lang={lang},{ext}" for lang, ext in CLOC_FORCED_LANGUAGES]
        subprocess.run(command, cwd=cwd, check=True, capture_output=True)
        return json.loads(out_file.read_text(encoding="utf-8"))


def build_report(tree: Tree) -> Report:
    report = Report(missing_submodules=list(tree.missing_submodules), head=tree.label, date=tree.date,
                    subject=tree.subject, first_party_bytes=tree.first_party_bytes)
    if not tree.files:
        return report
    data = run_cloc(tree.files, tree.root)

    counted = set()
    for path, entry in data.items():
        if path in ("header", "SUM"):
            continue
        counted.add(path)
        suffix = PurePosixPath(path).suffix.lower()
        language = LANGUAGE_BY_SUFFIX.get(suffix, entry["language"])
        category, component, tree_name = classify(path)
        report.records.append(FileRecord(
            path=path,
            language=language,
            counts=Counts(1, entry["blank"], entry["comment"], entry["code"]),
            category=category,
            component=component,
            tree=tree_name,
            generated=CATEGORY_BY_KEY[category].first_party and is_generated(tree.root / path),
        ))
    for path in tree.files:
        if path not in counted:
            suffix = PurePosixPath(path).suffix.lower() or PurePosixPath(path).name
            report.uncounted[classify(path)[0]][suffix] += 1
    return report


