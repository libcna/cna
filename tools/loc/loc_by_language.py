#!/usr/bin/env python3
"""Lines-of-code report for the whole CNA repository, per language and per category.

Counts every git-tracked file (and, when they are checked out, the files of the git
submodules) with cloc, then splits the result into blank, comment and code lines per
language and per repository category: production library, build system, tests, examples,
benchmarks, tools, scripts, CI, spikes, third-party patches, documentation, vendored
third-party sources and external submodules.

The counting engine is cloc (https://github.com/AlDanial/cloc, ``apt-get install cloc``);
this script only decides which file belongs where. ``loc.sh`` at the repository root runs it
and prints the same report as plain-text tables.

Definitions:
- A code line holds anything other than whitespace or a comment (code with a trailing comment
  is code), a comment line only a comment, a blank line only whitespace. Comment ratio is
  comment / (comment + code). Every tracked file counts once; duplicates count too.
- Source code is programming, shader (HLSL, GLSL) and build/config languages (CMake, YAML,
  TOML, ...). Markup (Markdown, text, HTML) and data (JSON, glTF, XML, CSV, patches, DirectX
  .x models) are counted but reported beside source code, never added into it.
- C++ is .cpp/.cc plus the generated .inc C API routes, C++ Header is .hpp, and C/C++ Header
  is .h, which in CNA is the C ABI of modules/c-api.
- A first-party file is generated when one of its first 12 lines is a comment saying so
  (GENERATED FILE, AUTO-GENERATED by, Do not edit, @generated). Generated files are in every
  total; the hand-written rows leave them out.
- The category comes from the path (the report lists the rules). A module's root is the
  directory just above its first well-known subtree (include, src, tests, ...), so nested
  modules such as modules/renderers/common/mojoshader get their own row.

Usage:
    ./loc.sh                                             # the report as text tables
    ./loc.sh --no-submodules                             # first-party and vendored only; faster
    python3 tools/loc/loc_by_language.py                 # Markdown report on stdout
    python3 tools/loc/loc_by_language.py --json loc.json # raw per-file data as well
    python3 tools/loc/loc_by_language.py --rev <commit>  # count a commit instead of the tree
    python3 tools/loc/loc_by_language.py --compare <base> --rev <commit> --per-commit
                                                         # change report, attributed per commit

Submodules that are not checked out are listed as not counted; run
``git submodule update --init --depth 1`` first to include them. Dependencies fetched at
configure time (FNA3D, MojoShader, wgpu-native, ...) are not in the repository and not counted.
"""

