# plan_gltf.md GLTF-406: CNA's chosen licence policy is that every committed glTF/GLB container is
# CNA-generated corpus output. Real-world third-party models are fetched on demand by
# fetch-gltf-sample-assets.sh and never copied into the repository.

set -euo pipefail

REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
readonly REPO_ROOT
cd "$REPO_ROOT"

if ! command -v git >/dev/null 2>&1 || ! git rev-parse --git-dir >/dev/null 2>&1; then
    printf '%s\n' "check-gltf-asset-provenance: a Git checkout is required" >&2
    exit 2
fi

# `--check` compares the directory in both directions: every generated byte must match, and no
# extra file may hide among the corpus outputs. This is what makes the allowed prefix meaningful.
scripts/regenerate-gltf-goldens.sh --check >/dev/null

tracked_count=0
unexpected_assets=()
while IFS= read -r -d '' tracked_path; do
    ((tracked_count += 1))
    case "$tracked_path" in
        tests/assets/gltf/*.gltf|tests/assets/gltf/*.glb) ;;
        *) unexpected_assets+=("$tracked_path") ;;
    esac
done < <(git ls-files -z -- ':(icase)*.gltf' ':(icase)*.glb')

if (( tracked_count == 0 )); then
    printf '%s\n' "check-gltf-asset-provenance: no tracked glTF containers found" >&2
    exit 1
fi

if (( ${#unexpected_assets[@]} != 0 )); then
    printf '%s\n' \
        "check-gltf-asset-provenance: tracked containers outside the CNA-generated corpus:" >&2
    printf '  %s\n' "${unexpected_assets[@]}" >&2
    printf '%s\n' \
        "Third-party models must remain fetch-on-demand. Do not add an exception without the GLTF-018 per-asset licence and attribution review." >&2
    exit 1
fi

printf 'check-gltf-asset-provenance: %d tracked containers are CNA-generated; no third-party glTF asset is committed.\n' \
    "$tracked_count"
