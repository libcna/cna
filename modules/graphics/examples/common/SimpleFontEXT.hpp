    /**
     * @brief Builds a real, readable 5x7 dot-matrix SpriteFont covering printable ASCII 32-126.
     *
     * Unlike the old per-demo MakeSimpleFont() (uniform-rectangle "block font", no letterform
     * differentiation), each character here samples its own distinct region of a real bitmap
     * glyph atlas, so DrawString output is genuinely readable text, not just correctly-spaced
     * blocks.
     */
    inline std::unique_ptr<Microsoft::Xna::Framework::Graphics::SpriteFont> MakeSimpleFontEXT(
        Microsoft::Xna::Framework::Graphics::GraphicsDevice& device)
    {
        using Microsoft::Xna::Framework::Rectangle;
        using Microsoft::Xna::Framework::Vector3;
        using Microsoft::Xna::Framework::Graphics::SpriteFont;
        using Microsoft::Xna::Framework::Graphics::Texture2D;

        constexpr int kCharCount = static_cast<int>(Detail::kGlyphRows.size());
        const int atlasWidth = kCharCount * Detail::kGlyphWidth;
        const int atlasHeight = Detail::kGlyphHeight;

        std::vector<std::uint8_t> pixels(
            static_cast<std::size_t>(atlasWidth) * static_cast<std::size_t>(atlasHeight) * 4, 0);
        for (int glyphIndex = 0; glyphIndex < kCharCount; ++glyphIndex)
        {
            const auto& rows = Detail::kGlyphRows[static_cast<std::size_t>(glyphIndex)];
            for (int row = 0; row < Detail::kGlyphHeight; ++row)
            {
                for (int col = 0; col < Detail::kGlyphWidth; ++col)
                {
                    const bool lit = ((rows[static_cast<std::size_t>(row)] >> (Detail::kGlyphWidth - 1 - col)) & 1) != 0;
                    if (!lit)
                    {
                        continue;
                    }
                    const int x = glyphIndex * Detail::kGlyphWidth + col;
                    const int y = row;
                    const std::size_t pixelIndex =
                        (static_cast<std::size_t>(y) * static_cast<std::size_t>(atlasWidth) + static_cast<std::size_t>(x)) * 4;
                    pixels[pixelIndex + 0] = 255;
                    pixels[pixelIndex + 1] = 255;
                    pixels[pixelIndex + 2] = 255;
                    pixels[pixelIndex + 3] = 255;
                }
            }
        }

        Texture2D atlas = Texture2D::CreateFromPixels(device, atlasWidth, atlasHeight, pixels);

        std::vector<SharpRuntime::charcs> chars;
        std::vector<Rectangle> bounds;
        std::vector<Rectangle> cropping;
        std::vector<Vector3> kerning;
        chars.reserve(static_cast<std::size_t>(kCharCount));
        bounds.reserve(static_cast<std::size_t>(kCharCount));
        cropping.reserve(static_cast<std::size_t>(kCharCount));
        kerning.reserve(static_cast<std::size_t>(kCharCount));
        for (int glyphIndex = 0; glyphIndex < kCharCount; ++glyphIndex)
        {
            chars.push_back(static_cast<SharpRuntime::charcs>(32 + glyphIndex));
            // `bounds` (SpriteFont's glyphData) is both the atlas source rect DrawString samples
            // from AND the size it draws the glyph at (matching FNA's own SpriteBatch.DrawString,
            // where cGlyph.Width/Height feed the destination rect) - this is exactly the field
            // the old MakeSimpleFont got wrong by using the same (0,0,1,1) rect for every
            // character regardless of its actual shape.
            bounds.emplace_back(glyphIndex * Detail::kGlyphWidth, 0, Detail::kGlyphWidth, Detail::kGlyphHeight);
            cropping.emplace_back(0, 0, Detail::kGlyphWidth, Detail::kGlyphHeight);
            kerning.emplace_back(0.0f, static_cast<float>(Detail::kGlyphAdvance), 0.0f);
        }

        return std::make_unique<SpriteFont>(atlas, bounds, cropping, chars, Detail::kGlyphHeight + 1,
                                             0.0f, kerning, static_cast<SharpRuntime::charcs>(' '));
    }
