TEST(ColorConstantContractTest, ScalarLeftMultiplyHasAnIndependentLiteralResult)
{
    const Color value(10, 20, 30, 40);
    EXPECT_EQ((0.5f * value).getPackedValueProperty(), 0x140f0a05u);
}
