TEST(CnbModelV2GoldenVectorTest, WriterMatchesIndependentSpecificationBytes)
{
    static_assert(Cnb::CnbModelV2SchemaVersion == 2u);
    ASSERT_EQ(kGoldenModelV2.size(), 1468u);
    ExpectBytesEqual(kGoldenModelV2,
                     Cnb::EncodeModelV2ToCnb(GoldenModelV2Value(), "golden/model-v2"));
}

TEST(CnbModelV2GoldenVectorTest, IndependentBytesDecodeToDocumentedSemantics)
{
    const Cnb::CnbDocument document =
        Cnb::CnbDocument::Parse(kGoldenModelV2, "golden-model-v2.cnb");
    EXPECT_EQ(document.AssetTypeId(), Cnb::CnbAssetTypeId::Model);
    EXPECT_EQ(document.AssetSchemaVersion(), 2u);
    EXPECT_EQ(document.ChunkCount(), 13u);
    ASSERT_EQ(document.ExternalReferences().size(), 1u);
    EXPECT_EQ(document.ExternalReferences()[0].logicalName, "Textures/checker");
    EXPECT_EQ(document.ExternalReferences()[0].expectedAssetTypeId,
              Cnb::CnbAssetTypeId::Texture2D);
    EXPECT_EQ(document.Metadata().contentName, "golden/model-v2");
    EXPECT_EQ(Cnb::DecodeModelV2FromCnb(document), GoldenModelV2Value());
}

TEST(CnbModelV2GoldenVectorTest, RawGeometryChunksUseSixteenByteAlignment)
{
    const Cnb::CnbDocument document =
        Cnb::CnbDocument::Parse(kGoldenModelV2, "golden-model-v2.cnb");
    const auto vertex = document.FindAll(Cnb::CnbModelV2Chunk::VertexData);
    const auto index = document.FindAll(Cnb::CnbModelV2Chunk::IndexData);
    ASSERT_EQ(vertex.size(), 1u);
    ASSERT_EQ(index.size(), 1u);
    EXPECT_EQ(document.ChunkAt(vertex[0]).alignment, 16u);
    EXPECT_EQ(document.ChunkAt(vertex[0]).offset % 16u, 0u);
    EXPECT_EQ(document.ChunkAt(index[0]).alignment, 16u);
    EXPECT_EQ(document.ChunkAt(index[0]).offset % 16u, 0u);
}
