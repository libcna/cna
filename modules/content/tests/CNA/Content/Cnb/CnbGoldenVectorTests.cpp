TEST(CnbGoldenVectorTest, TheModelVectorDecodesToItsDocumentedValues)
{
    const CnbDocument document = CnbDocument::Parse(kGoldenModel, "golden-model.cnb");
    EXPECT_EQ(document.AssetTypeId(), CnbAssetTypeId::Model);
    EXPECT_EQ(document.AssetSchemaVersion(), 1u);
    EXPECT_EQ(document.ChunkCount(), 8u);

    // The container-level reference table, readable without any schema knowledge.
    ASSERT_EQ(document.ExternalReferences().size(), 1u);
    EXPECT_EQ(document.ExternalReferences()[0].logicalName, "Textures/wall");
    EXPECT_EQ(document.ExternalReferences()[0].expectedAssetTypeId, CnbAssetTypeId::Texture2D);

    const CNA::Content::Cnb::CnbModelData model =
        CNA::Content::Cnb::DecodeModelFromCnb(document);
    EXPECT_TRUE(model.bones.empty());
    EXPECT_FALSE(model.hasBoneHierarchy);
    EXPECT_FALSE(model.appliesGltfLightingPolicy);
    EXPECT_FALSE(model.skeleton.has_value());
    EXPECT_TRUE(model.animations.empty());
    EXPECT_TRUE(model.lights.empty());

    ASSERT_EQ(model.parts.size(), 1u);
    const CNA::Content::Cnb::CnbModelPart& part = model.parts[0];
    EXPECT_EQ(part.name, "Hull");
    EXPECT_EQ(part.vertexStride, 16u);
    EXPECT_EQ(part.vertexCount, 3u);
    EXPECT_EQ(part.indexCount, 3u);
    EXPECT_EQ(part.indexElementSize, 2u);
    EXPECT_EQ(part.primitiveTopology, 4u);
    EXPECT_EQ(part.primitiveCount, 1u);
    EXPECT_EQ(part.effectKind, CNA::Content::Cnb::CnbEffectKind::BasicEffect);
    EXPECT_TRUE(part.externalEffect.empty());
    EXPECT_FALSE(part.vertexColorEnabled);
    EXPECT_FALSE(part.unlit);
    EXPECT_FALSE(part.morph.has_value());
    EXPECT_EQ(part.material.baseColorTexture, "Textures/wall");
    EXPECT_TRUE(part.material.normalMap.empty());

    // Every material default, spelled out. These are the bytes that would drift in silence: a
    // changed default is invisible in a round-trip test, which encodes and decodes the same
    // wrong value.
    EXPECT_FLOAT_EQ(part.material.baseColorFactor[0], 1.0f);
    EXPECT_FLOAT_EQ(part.material.baseColorFactor[3], 1.0f);
    EXPECT_FLOAT_EQ(part.material.emissiveFactor[0], 0.0f);
    EXPECT_FLOAT_EQ(part.material.specularColorFactor[2], 1.0f);
    EXPECT_FLOAT_EQ(part.material.metallicFactor, 1.0f);
    EXPECT_FLOAT_EQ(part.material.roughnessFactor, 1.0f);
    EXPECT_FLOAT_EQ(part.material.ior, 1.5f);
    EXPECT_FLOAT_EQ(part.material.specularFactor, 1.0f);
    EXPECT_FLOAT_EQ(part.material.normalScale, 1.0f);
    EXPECT_FLOAT_EQ(part.material.occlusionStrength, 1.0f);
    EXPECT_FLOAT_EQ(part.material.alphaCutoff, 0.5f);
    EXPECT_EQ(part.material.alphaMode, 0u);
    EXPECT_FALSE(part.material.doubleSided);
    for (std::size_t slot = 0; slot < CNA::Content::Cnb::CnbTextureSlotCount; ++slot)
    {
        EXPECT_EQ(part.material.textureCoordinateSets[slot], 0u) << "slot " << slot;
        EXPECT_FLOAT_EQ(part.material.textureTransforms[slot].scaleX, 1.0f) << "slot " << slot;
        EXPECT_FLOAT_EQ(part.material.textureTransforms[slot].offsetX, 0.0f) << "slot " << slot;
        EXPECT_FALSE(part.material.samplers[slot].declared) << "slot " << slot;
    }

    ASSERT_EQ(model.meshes.size(), 1u);
    EXPECT_EQ(model.meshes[0].name, "Hull");
    EXPECT_EQ(model.meshes[0].parentBone, -1);
    EXPECT_EQ(model.meshes[0].partIndices, std::vector<std::uint32_t>{0u});
}

