namespace
{
    XnbHeader ParseBytes(const std::vector<uint8_t>& bytes)
    {
        System::IO::MemoryStream ms(bytes.data(), static_cast<int32_t>(bytes.size()));
        System::IO::BinaryReader reader(&ms, true);
        return ParseXnbHeader(reader, "test.xnb");
    }
}

TEST(XnbHeaderTest, RealMonoGameFixtureHeaderParsesCorrectly)
{
    // First 10 bytes of MonoGame's own Tests/Assets/Textures/white-1.xnb (191-byte file),
    // produced by real MonoGame content-pipeline tooling, never generated by CNA.
    const std::vector<uint8_t> bytes{
        'X', 'N', 'B', 'w', 0x05, 0x00, 0xbf, 0x00, 0x00, 0x00
    };

    const XnbHeader header = ParseBytes(bytes);

    EXPECT_EQ(header.platform, 'w');
    EXPECT_EQ(header.version, 5);
    EXPECT_EQ(header.compression, XnbCompression::None);
    EXPECT_EQ(header.totalLength, 191);
}

TEST(XnbHeaderTest, LzxCompressedFlagBitIsDetected)
{
    const std::vector<uint8_t> bytes{
        'X', 'N', 'B', 'w', 0x05, 0x80, 0x10, 0x00, 0x00, 0x00
    };

    const XnbHeader header = ParseBytes(bytes);

    EXPECT_EQ(header.compression, XnbCompression::Lzx);
}

TEST(XnbHeaderTest, Lz4CompressedFlagBitIsDetected)
{
    // XNB-27: flags bit 0x40, confirmed against MonoGame's own ContentManager.cs
    // (ContentCompressedLz4 = 0x40) -- FNA itself never produces this, but MonoGame's content
    // pipeline can.
    const std::vector<uint8_t> bytes{
        'X', 'N', 'B', 'd', 0x05, 0x40, 0x10, 0x00, 0x00, 0x00
    };

    const XnbHeader header = ParseBytes(bytes);

    EXPECT_EQ(header.compression, XnbCompression::Lz4);
}

