TEST(XnbHeaderTest, EveryAcceptedPlatformParses)
{
    for (const char platform : CNA::Internal::Xnb::XnbAcceptedPlatforms())
    {
        const std::vector<uint8_t> bytes{
            'X', 'N', 'B', static_cast<uint8_t>(platform), 0x05, 0x00, 0x0a, 0x00, 0x00, 0x00
        };
        const XnbHeader header = ParseBytes(bytes);
        EXPECT_EQ(header.platform, platform);
    }
}

