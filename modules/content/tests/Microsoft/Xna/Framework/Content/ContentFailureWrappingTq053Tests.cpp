    class FaultStream final : public System::IO::MemoryStream
    {
    public:
        FaultStream(std::exception_ptr cause, bool length) : cause_(cause), length_(length) {}
        System::IO::intcs Read(System::IO::bytecs[], System::IO::intcs, System::IO::intcs) override
        { std::rethrow_exception(cause_); }
        System::IO::intcs getLengthProperty() const override
        {
            if (length_) std::rethrow_exception(cause_);
            return 0;
        }
    private:
        std::exception_ptr cause_;
        bool length_;
    };
    // A stream whose CanRead (or, readable, CanSeek) getter fails.
    class CapabilityFaultStream final : public System::IO::MemoryStream
    {
    public:
        CapabilityFaultStream(std::exception_ptr cause, bool canRead) : cause_(cause), canRead_(canRead) {}
        bool getCanReadProperty() const override
        {
            if (canRead_) std::rethrow_exception(cause_);
            return true;
        }
        bool getCanSeekProperty() const override
        {
            if (!canRead_) std::rethrow_exception(cause_);
            return true;
        }
    private:
        std::exception_ptr cause_;
        bool canRead_;
    };
    template<class Action>
    void ExpectFailure(Action action, std::exception_ptr cause, bool wrap)
    {
        try { action(); FAIL() << "expected injected failure"; }
        catch (const ContentLoadException& error)
        {
            if (!wrap) { EXPECT_EQ(std::current_exception(), cause); return; }
            // Refresh ReadAsset IL_0019-002c; CreateContentLoadException IL_0024-0026;
            // exact FrameworkResources.BadXnb = Error loading "{0}".
            EXPECT_EQ(typeid(error), typeid(ContentLoadException));
            EXPECT_EQ(error.getMessageProperty(), "Error loading \"asset\".");
            EXPECT_STREQ(error.what(), "Error loading \"asset\".");
            EXPECT_EQ(error.getInnerExceptionProperty(), cause);
        }
        catch (...) { EXPECT_FALSE(wrap); EXPECT_EQ(std::current_exception(), cause); }
    }
    struct Failure { std::exception_ptr cause; bool wrap; };
    std::vector<Failure> Failures()
    {
        return {
            {std::make_exception_ptr(System::IO::IOException("IO sentinel")), true},
            {std::make_exception_ptr(System::IO::EndOfStreamException("EOF sentinel")), true},
            {std::make_exception_ptr(System::InvalidOperationException("state sentinel")), false},
            {std::make_exception_ptr(System::NotSupportedException("format sentinel")), false},
            {std::make_exception_ptr(System::ObjectDisposedException("device sentinel")), false},
            {std::make_exception_ptr(System::ArgumentException("argument sentinel", "format")), false},
            {std::make_exception_ptr(System::UnauthorizedAccessException("access sentinel")), false},
            {std::make_exception_ptr(ContentLoadException("already wrapped",
                std::make_exception_ptr(System::IO::IOException("nested cause")))), false}
        };
    }
